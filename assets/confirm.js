// Landing page for the crash-course email-confirmation link. Deliberately
// does NOT auto-send on page load — email clients and corporate security
// scanners routinely pre-fetch links inside emails, which would silently
// "confirm" requests nobody actually asked for. The visitor has to click
// an explicit button here.

import { verifyConfirmParams } from './confirm-link.js';
import {
  EMAILJS_PUBLIC_KEY,
  EMAILJS_SERVICE_ID,
  EMAILJS_TEMPLATE_DELIVER,
  COURSE_FILES,
  NOTIFY_EMAIL,
} from './email-config.js';

const states = {
  checking: document.querySelector('[data-state="checking"]'),
  invalid: document.querySelector('[data-state="invalid"]'),
  ask: document.querySelector('[data-state="ask"]'),
  done: document.querySelector('[data-state="done"]'),
  fail: document.querySelector('[data-state="fail"]'),
};

function show(name) {
  Object.entries(states).forEach(([key, el]) => { el.hidden = key !== name; });
}

const params = new URLSearchParams(location.search);
const email = params.get('email') || '';
const course = params.get('course') || '';
const ts = params.get('ts') || '';
const sig = params.get('sig') || '';

const INVALID_COPY = {
  missing: {
    title: 'This link is incomplete.',
    body: "It's missing information it needs to work — try requesting the download again from the site.",
  },
  invalid: {
    title: "This link isn't valid.",
    body: 'Something about it is malformed — try requesting the download again from the site.',
  },
  signature: {
    title: "This link doesn't check out.",
    body: "It may have been altered, or it wasn't generated by the site. Try requesting the download again.",
  },
  expired: {
    title: 'This link has expired.',
    body: 'Confirmation links are only valid for 7 days. Head back and request the download again — it only takes a moment.',
  },
};

async function init() {
  const result = await verifyConfirmParams({ email, course, ts, sig });

  if (!result.valid) {
    const copy = INVALID_COPY[result.reason] || INVALID_COPY.invalid;
    document.querySelector('[data-invalid-title]').textContent = copy.title;
    document.querySelector('[data-invalid-body]').textContent = copy.body;
    show('invalid');
    return;
  }

  document.querySelectorAll('[data-course-name], [data-course-name-2], [data-course-name-3]').forEach((el) => {
    el.textContent = course;
  });
  document.querySelectorAll('[data-email-display], [data-email-display-2], [data-email-display-3]').forEach((el) => {
    el.textContent = email;
  });

  show('ask');

  const confirmBtn = document.querySelector('[data-confirm-btn]');
  const askError = document.querySelector('[data-ask-error]');
  const retryBtn = document.querySelector('[data-retry-btn]');

  async function send() {
    confirmBtn.disabled = true;
    confirmBtn.textContent = 'Sending…';
    askError.hidden = true;

    const downloadPath = COURSE_FILES[course] || '';
    const downloadLink = downloadPath ? new URL(downloadPath, location.href).toString() : '';

    if (typeof emailjs === 'undefined' || EMAILJS_PUBLIC_KEY.startsWith('YOUR_')) {
      finish(false, downloadLink);
      return;
    }

    try {
      emailjs.init({ publicKey: EMAILJS_PUBLIC_KEY });
      await emailjs.send(EMAILJS_SERVICE_ID, EMAILJS_TEMPLATE_DELIVER, {
        to_email: email,
        course,
        download_link: downloadLink || 'Gabriel will follow up with this directly.',
      });
      finish(true, downloadLink);
    } catch (err) {
      console.warn('EmailJS send failed', err);
      finish(false, downloadLink);
    }
  }

  function finish(ok, downloadLink) {
    if (ok) {
      const body = document.querySelector('[data-done-body]');
      const downloadWrap = document.querySelector('[data-done-download]');
      if (downloadLink) {
        body.textContent = `I've sent ${course} to ${email} — and you can grab it right here too, no need to wait on the inbox.`;
        document.querySelector('[data-download-link]').href = downloadLink;
        downloadWrap.hidden = false;
      } else {
        body.textContent = `Thanks — I know to expect you. This course isn't quite ready for auto-delivery yet, so I'll follow up with ${course} at ${email} directly.`;
        downloadWrap.hidden = true;
      }
      show('done');
    } else {
      const body = document.querySelector('[data-fail-body]');
      const downloadWrap = document.querySelector('[data-fail-download]');
      if (downloadLink) {
        body.innerHTML = `Your link checked out fine, so here's the file directly — I just wasn't able to email a copy to <span class="email">${email}</span> right now.`;
        document.querySelector('[data-download-link-2]').href = downloadLink;
        downloadWrap.hidden = false;
      } else {
        body.innerHTML = `Your link checked out fine, but I wasn't able to send the email just now. Try again, or reach me directly at <a href="mailto:${NOTIFY_EMAIL}">${NOTIFY_EMAIL}</a>.`;
        downloadWrap.hidden = true;
      }
      show('fail');
      confirmBtn.disabled = false;
      confirmBtn.textContent = 'Confirm & send';
    }
  }

  confirmBtn.addEventListener('click', send);
  retryBtn.addEventListener('click', () => {
    show('ask');
    send();
  });
}

init();
